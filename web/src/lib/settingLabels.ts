/** Split `statusLine.maxWidth` into `["statusLine", "maxWidth"]`. */
function segments(key: string): string[] {
  return key
    .replace(/\[(\d+)\]/g, ".$1")
    .split(".")
    .filter(Boolean);
}

/** Capitalise a segment that has no translation, so it still reads as a label. */
function humanize(segment: string): string {
  const spaced = segment
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2")
    .replace(/_/g, " ")
    .trim();
  return spaced.charAt(0).toUpperCase() + spaced.slice(1);
}

/**
 * Chinese title for a settings key.
 *
 * Falls back to a humanised raw segment rather than an empty string: an
 * untranslated key should still be scannable, and the raw key is always shown
 * as the subtitle anyway.
 */
export function settingLabel(key: string, locale: "zh" | "en" = "zh"): string {
  const parts = segments(key);
  if (locale === "en") return parts.map(humanize).join(" · ");
  return parts.map((part) => SEGMENT_ZH[part] ?? humanize(part)).join(" · ");
}

/** Last segment of a key, used as the compact column title. */
export function settingLeaf(key: string, locale: "zh" | "en" = "zh"): string {
  const parts = segments(key);
  const leaf = parts[parts.length - 1] ?? key;
  return locale === "en" ? humanize(leaf) : (SEGMENT_ZH[leaf] ?? humanize(leaf));
}

/**
 * Chinese name for a settings tab id from `omp config list`.
 *
 * omp ships its own `appearance` tab (terminal theme, symbol preset, …) which
 * is a different thing from this app's appearance panel, so the label carries
 * omp's name to keep the two distinguishable in one list.
 */
export function tabLabel(tab: string, locale: "zh" | "en" = "zh"): string {
  const label = locale === "en" ? humanize(tab) : (SEGMENT_ZH[tab] ?? humanize(tab));
  if (tab !== "appearance") return label;
  return locale === "en" ? `${label} (omp)` : `${label}（omp）`;
}
